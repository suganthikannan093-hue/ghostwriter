import type { Spec } from "./schema";

/** Normalise a model-supplied file path so the zip can never escape its root. */
export function safePath(p: string): string | null {
  const parts = p.replace(/\\/g, "/").split("/").filter((x) => x && x !== "." && x !== "..");
  if (!parts.length) return null;
  const out = parts.join("/");
  if (out.startsWith(".kiro/")) return null; // .kiro is generated by us, not the model
  return out.length > 200 ? null : out;
}

export function slugify(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "resurrected-project";
}

/** Sanitise a parsed spec: safe paths, dedupe files, cap sizes, fix slug. */
export function sanitize(spec: Spec): Spec {
  const seen = new Set<string>();
  const files = [];
  for (const f of spec.files) {
    const p = safePath(f.path);
    if (!p || seen.has(p)) continue;
    seen.add(p);
    files.push({ path: p, content: f.content.slice(0, 20000) });
    if (files.length >= 25) break;
  }
  return { ...spec, slug: slugify(spec.slug || spec.projectName), files };
}
